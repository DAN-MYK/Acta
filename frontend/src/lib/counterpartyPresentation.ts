import { formatDocumentsLabel, formatLastContactLabel } from "./config/ui";

export function getCounterpartyOverdueDocumentsLabel(overdueCount: number): string {
  return formatDocumentsLabel(overdueCount);
}

export function getCounterpartyRiskLabel(overdueCount: number): string {
  if (overdueCount <= 0) {
    return "\u041f\u0440\u0430\u0446\u044e\u0454 \u0441\u0442\u0430\u0431\u0456\u043b\u044c\u043d\u043e";
  }

  return `\u041f\u043e\u0442\u0440\u0435\u0431\u0443\u0454 \u0443\u0432\u0430\u0433\u0438: \u043f\u0440\u043e\u0441\u0442\u0440\u043e\u0447\u0435\u043d\u043e ${getCounterpartyOverdueDocumentsLabel(overdueCount)}`;
}

export function getCounterpartyLastContactLabel(days: number): string {
  return formatLastContactLabel(days);
}

export function getCounterpartyScenarioTitle(
  overdueCount: number,
  lastContactDays: number,
  docCount: number
): string {
  if (overdueCount > 0) {
    return "\u0417\u0430\u043a\u0440\u0438\u0442\u0438 \u043f\u0440\u043e\u0441\u0442\u0440\u043e\u0447\u043a\u0443";
  }

  if (lastContactDays >= 21) {
    return "\u041e\u043d\u043e\u0432\u0438\u0442\u0438 \u043a\u043e\u043d\u0442\u0430\u043a\u0442";
  }

  if (docCount === 0) {
    return "\u0417\u0430\u043f\u0443\u0441\u0442\u0438\u0442\u0438 \u043f\u0435\u0440\u0448\u0438\u0439 \u0434\u043e\u043a\u0443\u043c\u0435\u043d\u0442";
  }

  return "\u0422\u0440\u0438\u043c\u0430\u0442\u0438 \u0441\u0446\u0435\u043d\u0430\u0440\u0456\u0439 \u0443 \u0440\u0443\u0441\u0456";
}

export function getCounterpartyScenarioDescription(
  overdueCount: number,
  overdueAmountStr: string,
  lastContactDays: number,
  docCount: number
): string {
  if (overdueCount > 0) {
    return `\u0404 ${getCounterpartyOverdueDocumentsLabel(overdueCount)} \u043d\u0430 ${overdueAmountStr}. \u0412\u0456\u0434\u043a\u0440\u0438\u0439\u0442\u0435 \u0434\u043e\u043a\u0443\u043c\u0435\u043d\u0442 \u0430\u0431\u043e \u0441\u0442\u0432\u043e\u0440\u0456\u0442\u044c \u043d\u043e\u0432\u0438\u0439, \u0449\u043e\u0431 \u043f\u043e\u0432\u0435\u0440\u043d\u0443\u0442\u0438 \u043a\u043e\u043d\u0442\u0440\u0430\u0433\u0435\u043d\u0442\u0430 \u0432 \u0440\u043e\u0431\u043e\u0447\u0438\u0439 \u0433\u0440\u0430\u0444\u0456\u043a.`;
  }

  if (lastContactDays >= 21) {
    return `\u041e\u0441\u0442\u0430\u043d\u043d\u0456\u0439 \u043a\u043e\u043d\u0442\u0430\u043a\u0442 \u0431\u0443\u0432 ${getCounterpartyLastContactLabel(lastContactDays)}. \u0412\u0430\u0440\u0442\u043e \u043e\u043d\u043e\u0432\u0438\u0442\u0438 \u0441\u0442\u0430\u0442\u0443\u0441 \u0434\u043e\u043c\u043e\u0432\u043b\u0435\u043d\u043e\u0441\u0442\u0435\u0439 \u0456 \u0437\u0430\u0444\u0456\u043a\u0441\u0443\u0432\u0430\u0442\u0438 \u043d\u0430\u0441\u0442\u0443\u043f\u043d\u0438\u0439 \u043a\u0440\u043e\u043a.`;
  }

  if (docCount === 0) {
    return "\u041f\u043e \u043a\u043e\u043d\u0442\u0440\u0430\u0433\u0435\u043d\u0442\u0443 \u0449\u0435 \u043d\u0435\u043c\u0430\u0454 \u0430\u043a\u0442\u0438\u0432\u043d\u0438\u0445 \u0434\u043e\u043a\u0443\u043c\u0435\u043d\u0442\u0456\u0432. \u0421\u0442\u0432\u043e\u0440\u0456\u0442\u044c \u043f\u0435\u0440\u0448\u0438\u0439 \u0434\u043e\u043a\u0443\u043c\u0435\u043d\u0442, \u0449\u043e\u0431 \u0437\u0430\u043f\u0443\u0441\u0442\u0438\u0442\u0438 \u043e\u043f\u0435\u0440\u0430\u0446\u0456\u0439\u043d\u0438\u0439 \u0441\u0446\u0435\u043d\u0430\u0440\u0456\u0439.";
  }

  return "\u041a\u043e\u043d\u0442\u0440\u0430\u0433\u0435\u043d\u0442 \u0431\u0435\u0437 \u043f\u0440\u043e\u0441\u0442\u0440\u043e\u0447\u043e\u043a \u0456 \u0437 \u0430\u043a\u0442\u0438\u0432\u043d\u0438\u043c \u0434\u043e\u043a\u0443\u043c\u0435\u043d\u0442\u043e\u043e\u0431\u0456\u0433\u043e\u043c. \u041c\u043e\u0436\u043d\u0430 \u043f\u0435\u0440\u0435\u0445\u043e\u0434\u0438\u0442\u0438 \u0434\u043e \u043d\u0430\u0441\u0442\u0443\u043f\u043d\u043e\u0433\u043e \u0434\u043e\u043a\u0443\u043c\u0435\u043d\u0442\u0430 \u0430\u0431\u043e \u043a\u043e\u043d\u0442\u0440\u043e\u043b\u044e \u043e\u0441\u0442\u0430\u043d\u043d\u0456\u0445 \u043e\u043f\u043b\u0430\u0442.";
}

export function getCounterpartyFinancialSummary(balanceIsNegative: boolean, overdueCount: number): string {
  if (overdueCount > 0) {
    return "\u041f\u043e\u0442\u043e\u0447\u043d\u0438\u0439 \u0441\u0442\u0430\u043d \u043f\u043e\u0442\u0440\u0435\u0431\u0443\u0454 \u0440\u0443\u0447\u043d\u043e\u0457 \u0443\u0432\u0430\u0433\u0438.";
  }

  if (balanceIsNegative) {
    return "\u0411\u0430\u043b\u0430\u043d\u0441 \u0432\u0456\u0434'\u0454\u043c\u043d\u0438\u0439, \u0430\u043b\u0435 \u0431\u0435\u0437 \u043f\u0440\u043e\u0441\u0442\u0440\u043e\u0447\u043e\u043a.";
  }

  return "\u0411\u0430\u043b\u0430\u043d\u0441 \u043f\u0456\u0434 \u043a\u043e\u043d\u0442\u0440\u043e\u043b\u0435\u043c, \u043a\u0440\u0438\u0442\u0438\u0447\u043d\u0438\u0445 \u0441\u0438\u0433\u043d\u0430\u043b\u0456\u0432 \u043d\u0435\u043c\u0430\u0454.";
}
